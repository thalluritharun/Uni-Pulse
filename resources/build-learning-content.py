"""Package supplied source text verbatim for offline learning (no runtime fetch)."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
read = lambda name: (root / 'resources' / name).read_bytes().decode('utf-8')
psct = read('PSCT-Unit-1-source-text.txt')
titles = ['Problem Identification and Framing', 'Requirements and Expected Outcomes',
          'Constraints and Assumptions', 'Problem Decomposition',
          'Abstraction and Relevant Information', 'Structured Problem Representation']
ids = ['framing', 'requirements', 'constraints', 'decomposition', 'abstraction', 'representation']
starts = [0] + [psct.index(f'\n{i + 1}. {title}') + 1 for i, title in enumerate(titles) if i]
ends = starts[1:] + [len(psct)]
psct_topics = [dict(id=key, title=title, text=psct[start:end])
               for key, title, start, end in zip(ids, titles, starts, ends)]
assert ''.join(t['text'] for t in psct_topics) == psct

ai = read('PEA103-AI-Interaction-Design-source-text.txt')
pages = ai.split('\f')
assert pages[-1] == ''
pages = [page + '\f' for page in pages[:-1]]
ai_titles = ['Foundations', 'Data & Knowledge', 'Models & Training', 'Local AI',
             'Applications, RAG & Agents', 'Production & Infrastructure',
             'Trust, Security & Economics', 'Frontier & Reference']
ai_ids = ['ai-foundations', 'ai-data', 'ai-models', 'ai-local', 'ai-applications',
          'ai-production', 'ai-trust', 'ai-reference']
ai_starts = [0, 5, 11, 19, 23, 32, 40, 44]
ai_ends = ai_starts[1:] + [len(pages)]
ai_topics = []
for key, title, start, end in zip(ai_ids, ai_titles, ai_starts, ai_ends):
    ai_topics.append(dict(id=key, title=title, pages=[dict(number=i+1, text=pages[i]) for i in range(start,end)]))
assert ''.join(p['text'] for t in ai_topics for p in t['pages']) == ai
payload = [dict(subjectId='pea101', title='Problem Understanding and Representation',
                sourceUrl='resources/PSCT-Unit-1-source-text.txt', sourceFormat='text', topics=psct_topics),
           dict(subjectId='pea103', title='The Complete AI Ecosystem', sourceFormat='pdf',
                sourceUrl='resources/PEA103-AI-Interaction-Design.pdf', topics=ai_topics)]
bundle = '/* Complete supplied source text. Generated by resources/build-learning-content.py. */\n'
bundle += 'window.UNI_PULSE_SOURCE_RECORDS = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'js' / 'learning-sources.js').write_text(bundle, encoding='utf-8')
print(f'Packaged {len(psct):,} PEA 101 characters and {len(ai):,} PEA 103 characters, {len(pages)} PDF pages.')
